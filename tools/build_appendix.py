#!/usr/bin/env python3
"""Regenerate the appendix copies from the live files.

The appendix submitted with the thesis has to show the environment that actually
produced the work. Hand-copied files drift from the originals over the weeks of
implementation, and a drifted appendix is worse than none: it reports an
environment that never ran.

So the appendix is generated. Run this before submitting, and after any change
to a rule, a skill or the agent definition.

  python tools/build_appendix.py          # regenerate
  python tools/build_appendix.py --check  # fail if out of date (for CI)

appendix/README.md is written by hand and is never touched by this script.
"""

from __future__ import annotations

import argparse
import datetime
import pathlib
import sys

SUBTREE = pathlib.Path(__file__).resolve().parent.parent
REPO = SUBTREE.parent.parent
APPENDIX = SUBTREE / "appendix"

# (appendix filename, source path relative to repo root, what it is)
ITEMS = [
    ("A2_subtree-CLAUDE.md", "research/regression-testing/CLAUDE.md",
     "Directory-scoped rules, read automatically inside the subtree"),
    ("A3_agent-thesis-standard.md", ".claude/agents/thesis-standard.md",
     "Subagent definition for [STANDARD] tasks, model pinned to Opus 5"),
    ("A4_skill-thesis-plan.md", ".claude/skills/thesis-plan/SKILL.md",
     "The planning session"),
    ("A5_skill-thesis-resume.md", ".claude/skills/thesis-resume/SKILL.md",
     "The working session"),
    ("A6_skill-thesis-standard.md", ".claude/skills/thesis-standard/SKILL.md",
     "A cheaper session executing one specified task"),
    ("A7_skill-thesis-review.md", ".claude/skills/thesis-review/SKILL.md",
     "The review pass"),
]

# A1 is a section of the root CLAUDE.md rather than a file of its own.
ROOT_CLAUDE_SECTION = "## Thesis instrumentation"
A1 = ("A1_root-CLAUDE-addition.md", "CLAUDE.md",
      "The repo-wide block added to the root CLAUDE.md")

# The record-keeping documents accumulate content as the work proceeds, so the
# live files stop showing the environment as it started. These are the empty
# forms: everything up to the TEMPLATE-END marker, plus a fixed tail where the
# file needs its headings back. Truncating at a marker rather than keeping a
# separate hand-written copy is what stops the appendix forms and the real ones
# drifting into two different formats.
TEMPLATE_MARKER = "<!-- TEMPLATE-END"
TEMPLATE_DIR = "templates"

EMPTY_TAIL_OPEN_QUESTIONS = """
## Open

*(no questions recorded yet)*

---

## Resolved

<!-- Moved to DECISIONS.md. Keep the id and a one-line pointer. -->

*(none yet)*
"""

EMPTY_TAIL_PLAN = """
| Phase | Tasks | Done | Blocked |
|---|---|---|---|
| A — application instrumentation | — | — | — |
| B — pipeline stages 1 to 3.2 | — | — | — |
| C — analysis and pilot | — | — | — |
"""

# (appendix filename, source relative to repo root, tail, what it is)
TEMPLATES = [
    ("B1_IMPLEMENTATION_PLAN.md", "research/regression-testing/docs/IMPLEMENTATION_PLAN.md",
     EMPTY_TAIL_PLAN, "Task format and the three rules the plan must satisfy"),
    ("B2_OPEN_QUESTIONS.md", "research/regression-testing/docs/OPEN_QUESTIONS.md",
     EMPTY_TAIL_OPEN_QUESTIONS, "Form for questions awaiting the author's ruling"),
    ("B3_DECISIONS.md", "research/regression-testing/docs/DECISIONS.md",
     "", "Form for what was decided, when, by whom and why"),
    ("B4_IMPLEMENTATION_LOG.md", "research/regression-testing/docs/IMPLEMENTATION_LOG.md",
     "", "Form for where the difficulty and effort went"),
    ("B5_REVIEW_LOG.md", "research/regression-testing/docs/REVIEW_LOG.md",
     "", "Form for what was reviewed and accepted"),
]


def banner(source_rel, what):
    today = datetime.date.today().isoformat()
    return (
        "<!-- GENERATED by tools/build_appendix.py on " + today + ".\n"
        "     Source: " + source_rel + "\n"
        "     " + what + "\n"
        "     Edit the source, not this copy. -->\n\n"
    )


def root_section():
    """The thesis block of the root CLAUDE.md, without the rest of the file."""
    text = (REPO / "CLAUDE.md").read_text(encoding="utf-8")
    start = text.find(ROOT_CLAUDE_SECTION)
    if start < 0:
        sys.exit(
            "Could not find '" + ROOT_CLAUDE_SECTION + "' in the root CLAUDE.md.\n"
            "If the heading was renamed, update ROOT_CLAUDE_SECTION here."
        )
    # Runs to the next top-level heading, or to the end of the file.
    nxt = text.find("\n## ", start + len(ROOT_CLAUDE_SECTION))
    return text[start:] if nxt < 0 else text[start:nxt + 1]


def empty_form(src, tail):
    """A document's blank form: everything above TEMPLATE-END, plus its tail."""
    path = REPO / src
    if not path.is_file():
        sys.exit("Missing source: " + src)
    text = path.read_text(encoding="utf-8")
    cut = text.find(TEMPLATE_MARKER)
    if cut < 0:
        sys.exit(
            "No '" + TEMPLATE_MARKER + "' marker in " + src + ".\n"
            "The appendix forms are produced by truncating at it, so a file "
            "without one would be copied whole, entries and all."
        )
    return text[:cut].rstrip() + "\n" + tail


def build():
    out = {}
    name, src, what = A1
    out[name] = banner(src + " (section '" + ROOT_CLAUDE_SECTION + "')", what) + root_section()
    for name, src, what in ITEMS:
        path = REPO / src
        if not path.is_file():
            sys.exit("Missing source: " + src)
        out[name] = banner(src, what) + path.read_text(encoding="utf-8")
    for name, src, tail, what in TEMPLATES:
        out[TEMPLATE_DIR + "/" + name] = (
            banner(src + " (blank form)", what) + empty_form(src, tail)
        )
    return out


def strip_banner(text):
    end = text.find("-->")
    return text[end + 3:].lstrip("\n") if text.startswith("<!-- GENERATED") and end > 0 else text


def main():
    ap = argparse.ArgumentParser(description="Regenerate the thesis appendix copies.")
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if any copy is out of date")
    args = ap.parse_args()

    APPENDIX.mkdir(exist_ok=True)
    built = build()
    stale = []

    for name, content in sorted(built.items()):
        target = APPENDIX / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if args.check:
            current = target.read_text(encoding="utf-8") if target.is_file() else ""
            # The banner carries today's date, so compare the content below it.
            if strip_banner(current) != strip_banner(content):
                stale.append(name)
            continue
        target.write_text(content, encoding="utf-8", newline="\n")
        print("  wrote " + name)

    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale))
            print("Run: python tools/build_appendix.py")
            return 1
        print("Appendix is up to date (" + str(len(built)) + " files).")
        return 0

    print("\n" + str(len(built)) + " files regenerated in appendix/.")
    print("appendix/README.md is hand-written and was not touched.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
